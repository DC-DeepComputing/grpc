def put(rel, blob_b64, marker):
    p = os.path.join(ROOT, rel)
    data = base64.b64decode(blob_b64).decode()
    if os.path.exists(p):
        cur = open(p).read()
        if marker in cur:
            print('skip  ', rel, '(already patched)')
            return
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'w').write(data)
    print('write ', rel)

